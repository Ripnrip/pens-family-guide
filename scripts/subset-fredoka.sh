#!/usr/bin/env bash
# Rebuild src/brand/fonts/fredoka.ts (Fredoka 600, Latin + Latin-1 subset, WOFF2, base64).
# Needs: pip install --break-system-packages fonttools brotli
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
work="$(mktemp -d)"
curl -sSfL -o "$work/Fredoka.ttf" "https://raw.githubusercontent.com/google/fonts/main/ofl/fredoka/Fredoka%5Bwdth,wght%5D.ttf"
python3 -I -c "
import sys
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
instancer.instantiateVariableFont(TTFont(sys.argv[1]), {'wght': 600, 'wdth': 100}).save(sys.argv[2])
" "$work/Fredoka.ttf" "$work/Fredoka-600.ttf"
pyftsubset "$work/Fredoka-600.ttf" \
  --unicodes="U+0020-007E,U+00A0-00FF,U+2013-2014,U+2018-201D,U+2022,U+2026,U+20AC" \
  --flavor=woff2 --layout-features='kern,liga' --no-hinting --desubroutinize \
  --output-file="$here/src/brand/fonts/fredoka-600-latin.woff2"
b64="$(base64 -w0 "$here/src/brand/fonts/fredoka-600-latin.woff2")"
cat > "$here/src/brand/fonts/fredoka.ts" <<TS
/**
 * Fredoka SemiBold (600), static instance (wdth 100) subset to Basic Latin + Latin-1 (+ dashes,
 * curly quotes, bullet, ellipsis, euro), WOFF2. Generated by scripts/subset-fredoka.sh from
 * github.com/google/fonts ofl/fredoka (SIL Open Font License 1.1, see ./Fredoka-OFL.txt).
 * Inlined as a data: URI because widget CSPs block font fetches.
 */
export const FREDOKA_600_WOFF2_BASE64 =
  "$b64";
TS
rm -rf "$work"
echo "fredoka.ts: ${#b64} base64 chars"
