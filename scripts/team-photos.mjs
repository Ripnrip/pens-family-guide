#!/usr/bin/env node
// Builds src/content/teamPhotos.ts: each provider photo in public/assets/team/*.jpg becomes a
// 160x160 center-top WebP (quality 70) inlined as a data URI. Widgets have an empty CSP, so photos
// must be inline. Re-run after swapping a photo:
//   npm i --prefix /tmp/pens-brand-tools sharp && SHARP_DIR=/tmp/pens-brand-tools npm run team:photos
import { readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sharpDir = process.env.SHARP_DIR ? path.resolve(process.env.SHARP_DIR) : root;
const require = createRequire(path.join(sharpDir, "node_modules", "noop.js"));
const sharp = require("sharp");

const dir = path.join(root, "public", "assets", "team");
const files = readdirSync(dir).filter((f) => f.endsWith(".jpg")).sort();
const entries = [];
let total = 0;
for (const f of files) {
  const buf = await sharp(path.join(dir, f))
    .resize({ width: 160, height: 160, fit: "cover", position: "top" })
    .webp({ quality: 70, effort: 6 })
    .toBuffer();
  const uri = `data:image/webp;base64,${buf.toString("base64")}`;
  total += uri.length;
  entries.push(`  ${JSON.stringify(f.replace(/\.jpg$/, ""))}: ${JSON.stringify(uri)},`);
}

const out = `/**
 * GENERATED by scripts/team-photos.mjs from public/assets/team/*.jpg. Do not edit by hand.
 * 160x160 center-top WebP (quality 70) data URIs, keyed by TeamMember.photo. Inlined because widgets
 * have an empty CSP. Names and photos need PENS approval before public listing (see team.ts).
 */
export const TEAM_PHOTOS: Record<string, string> = {
${entries.join("\n")}
};
`;
writeFileSync(path.join(root, "src", "content", "teamPhotos.ts"), out);
console.log(`teamPhotos.ts: ${files.length} photos, ${(total / 1024).toFixed(1)} KB of data URIs`);
